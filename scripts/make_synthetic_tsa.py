#!/usr/bin/env python3
"""Write the synthetic sol-air temperature used until the real ttab file arrives.

T_sa(t) = 50 - 24 cos(2 pi t / 1 day) degC, sampled hourly from 0 to 72 h (26 to 74 degC;
starts at 26 degC, in equilibrium with the plate and the room). Agreed at kickoff (memory Q
"synthetic steel-plate signal"). Output: cases/steel_plate/synthetic_tsa.csv (t_s,T_sa_C).
Run: python3 scripts/make_synthetic_tsa.py
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "cases", "steel_plate", "synthetic_tsa.csv")


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("# Synthetic sol-air temperature: T_sa = 50 - 24 cos(2 pi t / 86400 s) degC, hourly.\n")
        f.write("# Generated by scripts/make_synthetic_tsa.py; stand-in for the real ttab file.\n")
        f.write("t_s,T_sa_C\n")
        for hour in range(73):
            t = 3600 * hour
            f.write(f"{t},{50.0 - 24.0 * math.cos(2.0 * math.pi * t / 86400.0):.10f}\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
